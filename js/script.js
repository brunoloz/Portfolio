document.addEventListener('DOMContentLoaded', () => {
  const year = document.getElementById('year');
  if (year) {
    year.textContent = new Date().getFullYear();
  }

  const languageButton = document.getElementById('language-toggle');
  const menuButton = document.getElementById('menu-toggle');
  const navigation = document.getElementById('main-nav');
  let currentLanguage = localStorage.getItem('portfolio-language') === 'en' ? 'en' : 'es';

  const setMenuOpen = (isOpen) => {
    navigation.hidden = !isOpen;
    menuButton.setAttribute('aria-expanded', String(isOpen));
    menuButton.setAttribute(
      'aria-label',
      translations[currentLanguage][isOpen ? 'nav-close' : 'nav-open'],
    );
  };

  menuButton.addEventListener('click', () => {
    setMenuOpen(menuButton.getAttribute('aria-expanded') !== 'true');
  });

  navigation.addEventListener('click', (event) => {
    if (event.target.closest('a')) {
      setMenuOpen(false);
    }
  });

  document.addEventListener('click', (event) => {
    if (
      menuButton.getAttribute('aria-expanded') === 'true'
      && !navigation.contains(event.target)
      && !menuButton.contains(event.target)
    ) {
      setMenuOpen(false);
    }
  });

  document.addEventListener('keydown', (event) => {
    if (event.key === 'Escape' && menuButton.getAttribute('aria-expanded') === 'true') {
      setMenuOpen(false);
      menuButton.focus();
    }
  });

  const setLanguage = (language) => {
    currentLanguage = language;
    document.documentElement.lang = language;
    document.title = translations[language]['page-title'];

    document.querySelectorAll('[data-i18n]').forEach((element) => {
      const key = element.dataset.i18n;
      element.textContent = translations[language][key];
    });

    document.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
      const key = element.dataset.i18nAriaLabel;
      element.setAttribute('aria-label', translations[language][key]);
    });

    document.querySelectorAll('[data-i18n-alt]').forEach((element) => {
      const key = element.dataset.i18nAlt;
      element.setAttribute('alt', translations[language][key]);
    });

    document.querySelector('meta[name="description"]').content = translations[language]['page-description'];
    languageButton.textContent = language === 'es' ? 'English' : 'Español';
    languageButton.setAttribute('aria-label', translations[language]['language-button-label']);
    menuButton.setAttribute(
      'aria-label',
      translations[language][menuButton.getAttribute('aria-expanded') === 'true' ? 'nav-close' : 'nav-open'],
    );
    renderBars('programming-stats', skillData.programming, language);
    renderBars('technical-skills', skillData.technical, language);
    renderBars('spoken-languages', skillData.languages, language);
  };

  languageButton.addEventListener('click', () => {
    const language = currentLanguage === 'es' ? 'en' : 'es';
    localStorage.setItem('portfolio-language', language);
    setLanguage(language);
  });

  setLanguage(currentLanguage);
});

function renderBars(chartId, values, language) {
  const chart = document.getElementById(chartId);

  if (!chart) {
    return;
  }

  chart.replaceChildren();

  values.forEach(({ name, level }) => {
    const item = document.createElement('li');
    const label = document.createElement('div');
    const languageLabel = document.createElement('span');
    const track = document.createElement('div');
    const fill = document.createElement('span');
    const displayName = typeof name === 'string' ? name : name[language];

    label.className = 'language-stat-label';
    languageLabel.textContent = displayName;
    track.className = 'language-stat-track';
    track.setAttribute('role', 'progressbar');
    track.setAttribute('aria-label', displayName);
    track.setAttribute('aria-valuemin', '0');
    track.setAttribute('aria-valuemax', '100');
    track.setAttribute('aria-valuenow', String(level));
    fill.className = 'language-stat-fill';
    fill.style.width = `${level}%`;

    label.append(languageLabel);
    track.append(fill);
    item.append(label, track);
    chart.append(item);
  });
}
